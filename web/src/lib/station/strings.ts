const ALL: Record<string, Strings> = { en, nl, fr, de };

export type StationKey = keyof Strings;

/** The page's strings for an app locale ("nl", "fr-BE", …), English when it has none. */
export function stationStrings(locale: string): Strings {
	return ALL[locale.split('-')[0] ?? 'en'] ?? en;
}

export function fill(template: string, params: Record<string, string | number> = {}): string {
	return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}
