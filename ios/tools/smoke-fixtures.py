#!/usr/bin/env python3
"""Writes KinframeTests/Support/SmokeFixtures.swift: for every GET of the API the family app may call, the smallest
answer that decodes (required fields only, first enum value, empty lists), from docs/api/openapi.yaml.

The smoke test (KinframeTests/SmokeTests.swift) answers every request it has no hand-written answer for with these,
so every screen gets past loading. Rerun after changing the API:

    python3 ios/tools/smoke-fixtures.py        (needs PyYAML)
"""
import json
import pathlib
import re

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
SPEC = ROOT / "docs/api/openapi.yaml"
OUT = ROOT / "ios/KinframeTests/Support/SmokeFixtures.swift"
# Frame devices, operators and other servers: not the family app's own screens.
SKIP = re.compile(r"^/(v1/device|v1/operator|v1/frame-app|federation)/")

spec = yaml.safe_load(SPEC.read_text())


def resolve(node):
    while isinstance(node, dict) and "$ref" in node:
        target = spec
        for part in node["$ref"].lstrip("#/").split("/"):
            target = target[part]
        node = target
    return node


def sample_string(schema):
    if "enum" in schema:
        return next(v for v in schema["enum"] if v is not None)
    if "const" in schema:
        return schema["const"]
    if schema.get("examples"):
        return schema["examples"][0]
    fmt = schema.get("format")
    if fmt == "date-time":
        return "2026-11-20T09:00:00Z"
    if fmt == "date":
        return "2026-11-20"
    if fmt in ("uri", "url"):
        return "https://smoke.kinframe.test/x"
    if fmt == "email":
        return "smoke@example.org"
    pattern = schema.get("pattern", "")
    if pattern == "^[0-9]{2}-[0-9]{2}$":
        return "11-20"
    if pattern.startswith("^[0-9]{4}-(0[1-9]"):
        return "2026-11"
    if pattern.startswith("^[0-2][0-9]:[0-5][0-9]"):
        return "07:00"
    if pattern == "^[0-9]{8}$":
        return "12345678"
    return "smoke"


def nullable(schema):
    schema = resolve(schema)
    kind = schema.get("type")
    if isinstance(kind, list) and "null" in kind:
        return True
    return any(resolve(o).get("type") == "null" for o in schema.get("oneOf", []) + schema.get("anyOf", []))


def sample(schema, depth=0):
    schema = resolve(schema)
    if depth > 12:
        return None
    if "allOf" in schema:
        merged = {"type": "object", "properties": {}, "required": []}
        for part in schema["allOf"]:
            part = resolve(part)
            merged["properties"].update(part.get("properties", {}))
            merged["required"] += part.get("required", [])
        return sample(merged, depth + 1)
    for key in ("oneOf", "anyOf"):
        if key in schema:
            disc = schema.get("discriminator")
            if disc and disc.get("mapping"):
                name, ref = next(iter(disc["mapping"].items()))
                value = sample({"$ref": ref}, depth + 1)
                value[disc["propertyName"]] = name
                return value
            options = [o for o in schema[key] if resolve(o).get("type") != "null"]
            value = sample(options[0], depth + 1) if options else None
            if disc and isinstance(value, dict):
                ref = options[0].get("$ref", "")
                value[disc["propertyName"]] = ref.split("/")[-1]
            return value
    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), "null")
    if kind is None and "properties" in schema:
        kind = "object"
    if kind == "object":
        props = schema.get("properties", {})
        # Required but nullable (cursors, optional links): null, the "nothing more" answer.
        return {name: None if nullable(props.get(name, {})) else sample(props.get(name, {}), depth + 1)
                for name in schema.get("required", [])}
    if kind == "array":
        return [sample(schema["items"], depth + 1)] if schema.get("minItems", 0) > 0 else []
    if kind == "string":
        return sample_string(schema)
    if kind == "integer":
        return int(schema.get("minimum", 0))
    if kind == "number":
        return float(schema.get("minimum", 0))
    if kind == "boolean":
        return False
    return {} if kind is None else None


def answers():
    for path, ops in spec["paths"].items():
        get = ops.get("get")
        if not get or not path.startswith("/v1/") or SKIP.match(path):
            continue
        code = next((c for c in get["responses"] if str(c).startswith("2")), None)
        if code is None:
            continue
        content = resolve(get["responses"][code]).get("content", {})
        if "application/json" not in content:
            continue
        yield path, sample(content["application/json"].get("schema", {}))


lines = [
    "// Generated by ios/tools/smoke-fixtures.py from docs/api/openapi.yaml. Do not edit; rerun the script.",
    "",
    "/// The smallest answer that decodes, per GET path template (see SmokeTests).",
    "enum SmokeFixtures {",
    "    static let get: [String: String] = [",
]
for path, body in sorted(answers()):
    lines.append(f'        "{path}": #"{json.dumps(body, ensure_ascii=False, separators=(",", ":"))}"#,')
lines += ["    ]", "}", ""]
OUT.write_text("\n".join(lines))
print(f"wrote {OUT.relative_to(ROOT)}")
