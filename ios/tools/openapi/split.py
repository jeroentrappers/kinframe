#!/usr/bin/env python3
"""Lays out the generator's Client.swift and Types.swift the way they are checked in (see ios/tools/generate-api.sh).

The import header becomes the Swift 6 form (`public import`) whatever toolchain ran the generator (on Linux it emits
`#if os(Linux) @preconcurrency import ...`), and Types.swift is split into Types.swift (the protocol and servers),
Types+Components*.swift (one file per components section) and Types+Operations.swift, so no file gets too big for
the editor and review tools. Usage: split.py <generator output dir> <destination dir>
"""
import re
import sys
from pathlib import Path

src, dst = Path(sys.argv[1]), Path(sys.argv[2])
dst.mkdir(parents=True, exist_ok=True)

HEADER = """// Generated by swift-openapi-generator, do not modify.
@_spi(Generated) public import OpenAPIRuntime
public import struct Foundation.URL
public import struct Foundation.Data
public import struct Foundation.Date
"""

# The Linux form, with plain imports (Swift 5 toolchains) or `public import` (Swift 6 toolchains).
OLD_HEADER = re.compile(
    r"\A// Generated by swift-openapi-generator, do not modify\.\n@_spi\(Generated\) (?:public )?import OpenAPIRuntime\n"
    r"#if os\(Linux\)\n(?:@preconcurrency (?:public )?import struct Foundation\.\w+\n)+#else\n"
    r"(?:(?:public )?import struct Foundation\.\w+\n)+#endif\n"
)


def body(text):
    if text.startswith(HEADER):
        return text[len(HEADER):]
    m = OLD_HEADER.match(text)
    if not m:
        raise SystemExit("split.py: unexpected header in the generated code")
    return text[m.end():]


# Generator versions that already write Types+Components*.swift and Types+Operations.swift only need the header.
if (src / "Types+Operations.swift").exists():
    for f in sorted(src.glob("*.swift")):
        (dst / f.name).write_text(HEADER + body(f.read_text()))
    sys.exit(0)

client = body((src / "Client.swift").read_text())
(dst / "Client.swift").write_text(HEADER + client)

types = body((src / "Types.swift").read_text()).split("\n")


def find(pred, start=0):
    for i in range(start, len(types)):
        if pred(types[i]):
            return i
    raise SystemExit("marker not found")


comp_doc = find(lambda l: l == "/// Types generated from the components section of the OpenAPI document.")
comp_open = comp_doc + 1
assert types[comp_open] == "public enum Components {"
comp_close = find(lambda l: l == "}", comp_open)
ops_doc = comp_close + 2

head = types[:comp_doc]
while head and head[-1] == "":
    head.pop()
(dst / "Types.swift").write_text(HEADER + "\n".join(head) + "\n")
(dst / "Types+Components.swift").write_text(
    HEADER + "/// Types generated from the components section of the OpenAPI document.\npublic enum Components {}\n"
)

# Sub-enums of Components: each starts at a doc comment line at 4 spaces followed by `public enum X`.
inner = types[comp_open + 1:comp_close]
sections = []
i = 0
while i < len(inner):
    if inner[i].startswith("    public enum "):
        name = inner[i].split()[2]
        start = i
        while start > 0 and inner[start - 1].startswith("    ///"):
            start -= 1
        if inner[i].endswith("{}"):
            end = i
        else:
            end = i + 1
            while inner[end] != "    }":
                end += 1
        sections.append((name, inner[start:end + 1]))
        i = end + 1
    else:
        i += 1
for name, lines in sections:
    (dst / f"Types+Components+{name}.swift").write_text(HEADER + "extension Components {\n" + "\n".join(lines) + "\n}\n")

ops = types[ops_doc:]
while ops and ops[-1] == "":
    ops.pop()
(dst / "Types+Operations.swift").write_text(HEADER + "\n".join(ops) + "\n")
