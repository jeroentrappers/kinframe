# Converts the wordmark SVG (web/static/logo-dark.svg, the light-on-dark variant the boot logo and boot animation are
# drawn from) into the Android VectorDrawable the frame app's start-up splash draws
# (android/frame/src/main/res/drawable/kinframe_wordmark.xml), so the splash shows the very same shapes:
#
#   python3 tools/brand/android/wordmark_vector.py
#
# The SVG is the source of truth; run this again after changing it. Only what the wordmark uses is supported: <rect>
# (with rx), <circle> and <path> with a solid fill. Path data is copied as it is (Android's path parser reads the
# same syntax); rectangles and circles become equivalent paths. The output is deterministic.
#
# SPDX-License-Identifier: AGPL-3.0-or-later
import argparse
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SVG_NS = "{http://www.w3.org/2000/svg}"


def num(v):
    f = float(v)
    return str(int(f)) if f == int(f) else repr(f)


def rect_path(x, y, w, h, rx):
    if rx <= 0:
        return f"M{num(x)},{num(y)}h{num(w)}v{num(h)}h{num(-w)}z"
    r = min(rx, w / 2, h / 2)
    return (
        f"M{num(x + r)},{num(y)}h{num(w - 2 * r)}a{num(r)},{num(r)} 0 0 1 {num(r)},{num(r)}"
        f"v{num(h - 2 * r)}a{num(r)},{num(r)} 0 0 1 {num(-r)},{num(r)}"
        f"h{num(-(w - 2 * r))}a{num(r)},{num(r)} 0 0 1 {num(-r)},{num(-r)}"
        f"v{num(-(h - 2 * r))}a{num(r)},{num(r)} 0 0 1 {num(r)},{num(-r)}z"
    )


def circle_path(cx, cy, r):
    return f"M{num(cx - r)},{num(cy)}a{num(r)},{num(r)} 0 1 1 {num(2 * r)},0a{num(r)},{num(r)} 0 1 1 {num(-2 * r)},0z"


def convert(svg: Path) -> str:
    root = ET.parse(svg).getroot()
    vx, vy, vw, vh = (float(v) for v in root.get("viewBox").split())
    if vx or vy:
        raise SystemExit("viewBox must start at 0 0")
    paths = []
    for el in root:
        tag = el.tag.replace(SVG_NS, "")
        fill = el.get("fill")
        if not fill or not fill.startswith("#"):
            raise SystemExit(f"<{tag}> needs a solid #rrggbb fill")
        a = {k: float(v) for k, v in el.attrib.items() if k in ("x", "y", "width", "height", "rx", "cx", "cy", "r")}
        if tag == "rect":
            d = rect_path(a.get("x", 0), a.get("y", 0), a["width"], a["height"], a.get("rx", 0))
        elif tag == "circle":
            d = circle_path(a["cx"], a["cy"], a["r"])
        elif tag == "path":
            d = el.get("d")
        else:
            raise SystemExit(f"unsupported element <{tag}>")
        paths.append(f'    <path\n        android:fillColor="{fill.upper().replace("#", "#FF")}"\n        android:pathData="{d}" />')
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- Generated by tools/brand/android/wordmark_vector.py from web/static/{svg.name}: do not edit by hand. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{num(vw)}dp"\n    android:height="{num(vh)}dp"\n'
        f'    android:viewportWidth="{num(vw)}"\n    android:viewportHeight="{num(vh)}">\n'
        + "\n".join(paths)
        + "\n</vector>\n"
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--svg", default=str(ROOT / "web/static/logo-dark.svg"))
    ap.add_argument("--out", default=str(ROOT / "android/frame/src/main/res/drawable/kinframe_wordmark.xml"))
    args = ap.parse_args()
    Path(args.out).write_text(convert(Path(args.svg)))


if __name__ == "__main__":
    main()
