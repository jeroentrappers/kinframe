// Command respgen emits methods so that api.Response satisfies every
// generated strict-server response interface. That lets handlers return
// hand-shaped JSON (raw settings documents, change feeds, problem bodies)
// without one wrapper type per operation.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: respgen <api.gen.go> <out.go>")
		os.Exit(2)
	}
	src, err := os.ReadFile(os.Args[1])
	if err != nil {
		panic(err)
	}
	re := regexp.MustCompile(`(?m)^\s+Visit(\w+)Response\(w http\.ResponseWriter\) error$`)
	seen := map[string]bool{}
	for _, m := range re.FindAllSubmatch(src, -1) {
		seen[string(m[1])] = true
	}
	names := make([]string, 0, len(seen))
	for n := range seen {
		names = append(names, n)
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/respgen. DO NOT EDIT.\n\npackage api\n\nimport \"net/http\"\n\n")
	for _, n := range names {
		fmt.Fprintf(&b, "func (r Response) Visit%sResponse(w http.ResponseWriter) error { return r.write(w) }\n", n)
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(os.Args[2], out, 0o644); err != nil {
		panic(err)
	}
}
